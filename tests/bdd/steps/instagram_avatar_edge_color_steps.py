# ── Then: the cost guarantees ───────────────────────────────────────────────


@then("no profile scrape is requested at all")
def step_no_scrape_at_all(context):
    apify, _ = _boundaries(context)
    assert apify.calls == [], (
        "the edge-colour backfill billed an Apify scrape; it must read the "
        f"photo it already has over the CDN. Calls: {apify.calls}"
    )


@then('no image is fetched for venue "{vid}"')
def step_no_image_fetched(context, vid):
    _, fetcher = _boundaries(context)
    row = _row(context, vid)
    url = (row.get("payload") or {}).get("photo_url") if row else None
    assert url not in fetcher.calls, f"{vid}: unexpected fetch of {url}"


@then('the image for venue "{vid}" was fetched from its stored CDN URL')
def step_image_fetched_from_cdn(context, vid):
    _, fetcher = _boundaries(context)
    url = _payload(context, vid)["photo_url"]
    assert url.startswith(settings.media_cdn_base_url.rstrip("/")), (
        f"{vid}: stored photo_url is not a CDN URL: {url!r}"
    )
    assert url in fetcher.calls, (
        f"{vid}: the backfill did not fetch {url}; fetched {fetcher.calls}"
    )
    assert _puts(context) == [], "the backfill uploaded an object"


@then('the profile photo row for venue "{vid}" is otherwise unchanged')
def step_row_otherwise_unchanged(context, vid):
    """Everything but `edge_color` must survive the backfill byte-for-byte.

    `content_hash` and `instagram_handle` are the load-bearing pair: they are
    what `_has_current_photo` reads, so rewriting either would make the next
    scheduled backfill re-buy an Apify scrape for every row this job touched.
    """
    data = context.stored_photo_bytes[vid]
    key, url = _cdn_url(vid, data)
    payload = _payload(context, vid)
    expected = {
        "venue_id": vid,
        "photo_url": url,
        "s3_key": key,
        "content_hash": hashlib.sha256(data).hexdigest(),
        "byte_size": len(data),
        "instagram_handle": context.handles.get(vid),
    }
    for field, want in expected.items():
        assert payload.get(field) == want, (
            f"{vid}.{field}: expected {want!r}, got {payload.get(field)!r}"
        )
    assert payload.get("edge_color"), f"{vid}: the backfill recorded no colour"


