@then("the trigger is rejected as an invalid mode")
def step_trigger_rejected(context):
    """Rejected, whichever shape the rejection takes.

    `run()` refuses BEFORE selection and reports the terminal status
    `invalid_mode` (a background job must not explode into APScheduler), while
    `estimate()` raises `InvalidProfilePhotoMode` outright. Both are the same
    behaviour under test — the mode was not silently resolved to a default —
    so the step accepts either and rejects anything else.
    """
    exc = getattr(context, "mode_rejection", None)
    if exc is not None:
        assert type(exc).__name__ == "InvalidProfilePhotoMode", (
            f"expected InvalidProfilePhotoMode, got {type(exc).__name__}: {exc}"
        )
        return
    summary = _summary(context)
    assert summary.get("status") == "invalid_mode", (
        "an unknown mode was accepted instead of rejected; run status was "
        f"{summary.get('status')!r}"
    )
    assert summary.get("venues_selected", 0) == 0, (
        "a rejected mode still selected venues"
    )
